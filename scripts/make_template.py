#!/usr/bin/env python3
"""Generate the contributor workbook from the CURRENT registries.

  python scripts/make_template.py [output.xlsx]      (default: templates/ingestion_template.xlsx)
  python scripts/make_template.py --example          (also writes templates/ingestion_example_filled.xlsx)

Dropdowns (events, metrics, publications, vocabularies) are filled from data/, so regenerate the template
after the registries change (CI checks it).  The workbook is only a data-entry form: scripts/ingest.py
validates and imports it.  Field definitions live in scripts/workbook_spec.py.
"""
import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.comments import Comment
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

sys.path.insert(0, str(Path(__file__).resolve().parent))
import schema                       # noqa: E402
import workbook_spec as ws_spec     # noqa: E402
from common import read_table      # noqa: E402

REQ = PatternFill("solid", fgColor="F4B183")      # required
WHEN = PatternFill("solid", fgColor="FFE699")     # required in some cases
OPT = PatternFill("solid", fgColor="DDEBF7")      # optional
LIST_HDR = PatternFill("solid", fgColor="E2EFDA")
BANDS = {ws_spec.IDENT: "5B7C99", ws_spec.VALUE: "3F7F6A", ws_spec.UNC: "8E6BA8", ws_spec.LOC: "B07A3C", ws_spec.METH: "6B6B6B"}
BOLD = Font(bold=True)
WRAP = Alignment(wrap_text=True, vertical="top")
FILL = {"yes": REQ, "when": WHEN, "": OPT}
LASTROW = 3000

HOWTO = [
    ("HOW TO USE THIS FILE", True),
    ("", False),
    ("1. One row = one value that a publication prints. Work in the INGESTION sheet; the colour bands group the columns as Identification / Value / Uncertainty / Location / Method.", False),
    ("2. Orange header = always required. Yellow = required in some cases (hover over the header: the note says when). Blue = optional.", False),
    ("3. Earthquake or paper missing from the dropdown? Add it in NEW_EVENTS or NEW_PUBLICATIONS first, then pick it in INGESTION. Another name for an existing earthquake: EVENT_ALIASES.", False),
    ("4. A series along a fault (table of values in a supplement): paste one row per measurement and give the SAME observation_group_id to all of them, statistic_type = individual. Longitude/latitude per row if available. The database stores it as one series and computes min/mean/median/max itself.", False),
    ("5. Never calculate anything. Do not derive OFD or SSD: enter them only if the paper publishes them, as percentages. Missing = empty cell, never 0.", False),
    ("6. Uncertainty: say what it is (uncertainty_type) and give POSITIVE offsets in uncertainty_minus / uncertainty_plus.", False),
    ("7. Check your file:   python scripts/ingest.py my_file.xlsx      (dry run, lists every problem with its row).  Then add  --apply --submitter \"Name (ORCID)\"  and open a pull request.", False),
    ("", False),
    ("record_id, submitted_by, submitted_on and review_status are generated by the database; do not enter them.", False),
    ("The FIELDS sheet lists every column. See docs/INGESTION_FIELDS.md for the full field guide. A filled example is in templates/ingestion_example_filled.xlsx (it cannot be imported).", False),
]


def style_header(ws, fields, lists, row_band=1, row_head=2, first_col=1, with_band=None):
    assert with_band is not None
    col = first_col
    for group, fs in with_band:
        start = col
        for name, req, width, lst, desc in fs:
            c = ws.cell(row=row_head, column=col, value=name)
            c.font, c.fill = BOLD, FILL[req]
            c.alignment = Alignment(wrap_text=True, vertical="center")
            c.comment = Comment(("REQUIRED. " if req == "yes" else "REQUIRED IN SOME CASES. " if req == "when" else "Optional. ") + desc, "database")
            c.comment.width, c.comment.height = 320, 130
            ws.column_dimensions[get_column_letter(col)].width = max(width, len(name) + 2)
            if lst:
                dv = DataValidation(type="list", formula1=lists[lst], allow_blank=True, showErrorMessage=True,
                                    errorStyle="warning", errorTitle="Value not in dropdown",
                                    error="This is a suggested list. Keep the free value if appropriate, or choose a listed value.")
                ws.add_data_validation(dv)
                dv.add(f"{get_column_letter(col)}{row_head + 1}:{get_column_letter(col)}{LASTROW}")
            col += 1
        b = ws.cell(row=row_band, column=start, value=group)
        for cc in range(start, col):
            ws.cell(row=row_band, column=cc).fill = PatternFill("solid", fgColor=BANDS[group])
        b.font = Font(bold=True, color="FFFFFF")
    ws.freeze_panes = f"A{row_head + 1}"


def side_sheet(wb, name, lists):
    ws = wb.create_sheet(name)
    for j, (n, req, width, lst, desc) in enumerate(ws_spec.SIDE_SHEETS[name], start=1):
        c = ws.cell(row=1, column=j, value=n)
        c.font, c.fill = BOLD, FILL[req]
        c.comment = Comment(("REQUIRED. " if req == "yes" else "REQUIRED IN SOME CASES. " if req == "when" else "Optional. ") + desc, "database")
        ws.column_dimensions[get_column_letter(j)].width = max(width, len(n) + 2)
        if lst:
            dv = DataValidation(type="list", formula1=lists[lst], allow_blank=True, showErrorMessage=True,
                    errorStyle="warning", errorTitle="Value not in dropdown",
                    error="This is a suggested list. Keep the free value if appropriate, or choose a listed value.")
            ws.add_data_validation(dv)
            dv.add(f"{get_column_letter(j)}2:{get_column_letter(j)}{LASTROW}")
    ws.freeze_panes = "A2"
    return ws


def build_workbook(example=False):
    ev, mt, so = read_table("events"), read_table("metrics"), read_table("sources")
    wb = Workbook()
    main = wb.active
    assert main is not None
    main.title = "INGESTION"
    lists_src = {
        "events": [f"{r.event_name} ({r.event_date or 'no date'}) [{r.event_id}]" for r in ev.itertuples()],
        "metrics": list(mt.metric_id),
        "pubs": [f"{r.citation_short} [{r.pub_id}]" for r in so.itertuples()],
        "statistics": ["individual", "minimum", "mean", "median", "maximum", "category"],
        "qualifiers": ["<", ">", "~"],
        "components": [c for c in schema.COMPONENTS if c],
        "unc_types": ["1_sigma", "2_sigma", "95_ci", "credible_interval", "range", "qualitative", "unspecified", "not_reported"],
        "methods": schema.METHODS,
        "verified": ["text", "table"],
        "quality": schema.QUALITY,
        "yesno": ["yes", "no"],
        "mechanisms": schema.MECHANISMS,
        "kinds": schema.KINDS,
        "origins": ["reported", "digitized"],
        "spatial": schema.SPATIAL_REPRESENTATIONS,
        "coord_origin": schema.COORD_ORIGINS,
    }
    ls = wb.create_sheet("LISTS")
    cells = {}
    for j, (name, vals) in enumerate(lists_src.items(), start=1):
        h = ls.cell(row=1, column=j, value=name)
        h.font, h.fill = BOLD, LIST_HDR
        for i, v in enumerate(vals, start=2):
            ls.cell(row=i, column=j, value=v)
        ls.column_dimensions[get_column_letter(j)].width = 36
        cells[name] = f"=LISTS!${get_column_letter(j)}$2:${get_column_letter(j)}${max(len(vals) + 1, 2) + 300}"
    style_header(main, None, cells, with_band=ws_spec.FIELDS)
    main.row_dimensions[2].height = 32
    for name in ("NEW_EVENTS", "NEW_PUBLICATIONS", "EVENT_ALIASES"):
        side_sheet(wb, name, cells)
    # FIELDS = the field dictionary (same layout as the contributor's own sheet)
    fs = wb.create_sheet("FIELDS")
    for j, h in enumerate(("Field", "Required?", "Description"), start=1):
        fs.cell(row=1, column=j, value=h).font = BOLD
    r = 2
    for group, fields in ws_spec.FIELDS:
        fs.cell(row=r, column=1, value=group).font = Font(bold=True, color="FFFFFF")
        for cc in range(1, 4):
            fs.cell(row=r, column=cc).fill = PatternFill("solid", fgColor=BANDS[group])
        r += 1
        for n, req, _, _, desc in fields:
            fs.cell(row=r, column=1, value=n)
            fs.cell(row=r, column=2, value={"yes": "Yes", "when": "When applicable", "": "Optional"}[req])
            c = fs.cell(row=r, column=3, value=desc)
            c.alignment = WRAP
            r += 1
    fs.column_dimensions["A"].width, fs.column_dimensions["B"].width, fs.column_dimensions["C"].width = 34, 16, 120
    ht = wb.create_sheet("HOW TO")
    ht.column_dimensions["A"].width = 150
    for i, (t, bold) in enumerate(HOWTO, start=1):
        c = ht.cell(row=i, column=1, value=t)
        c.alignment = WRAP
        if bold:
            c.font = Font(bold=True, size=13)
    ls.sheet_state = "hidden"
    order = ["INGESTION", "NEW_EVENTS", "NEW_PUBLICATIONS", "EVENT_ALIASES", "FIELDS", "HOW TO", "LISTS"]
    wb._sheets = [wb[n] for n in order]  # type: ignore[attr-defined]  # openpyxl exposes no public sheet-reordering API
    return wb, ev, so


def example_rows(ev, so):
    """Fictional values for a filled example. Every row carries [EXAMPLE] so the importer refuses the file."""
    e = ev[ev.event_name.str.contains("Ridgecrest 2")].event_id.iloc[0]
    p = "example_2099"
    base = dict(target_id=e, source_id=p, method="field", comments=ws_spec.EXAMPLE_MARK + " fictional")
    rows = [
        dict(base, metric_id="mapped_surface_rupture_length", statistic_type="individual", value=50, source_location="Table 1"),
        dict(base, metric_id="surface_fault_slip", statistic_type="maximum", value=3.2, component="strike-slip", uncertainty_type="1_sigma",
             uncertainty_minus=0.3, uncertainty_plus=0.5, source_location="Table 2, row 4", reported_text="3.2 +0.5/-0.3 m"),
        dict(base, metric_id="mapped_surface_rupture_length", statistic_type="individual", value_range_low=40, value_range_high=60,
             source_location="p. 5 text ('40-60 km')", model_id="range example"),
        dict(base, metric_id="surface_rupture_zone_width", statistic_type="maximum", value=14, qualifier="<", source_location="p. 6 text ('<14 m')"),
        dict(base, metric_id="earthquake_mechanism", statistic_type="category", value="Strike-slip", source_location="Abstract"),
        dict(base, metric_id="surface_fault_slip", statistic_type="mean", value=1.1, component="vertical/throw (source code T)", value_origin="digitized",
             digitization_method="WebPlotDigitizer, Fig. 3a", digitization_unc=0.2, source_location="Fig. 3a"),
    ]
    for i, (pos, v) in enumerate([(0, 0.8), (5, 1.4), (10, 2.1), (15, 1.7)], start=1):
        rows.append(dict(base, metric_id="surface_fault_slip", statistic_type="individual", value=v, component="strike-slip",
                         observation_group_id="series A", dataset_id="Example supplement S1", source_location="Supp. Table S1",
                         source_row_id=i, source_spatial_data=pos, source_spatial_unit="km", coordinate_origin="converted",
                         coordinate_conversion_method="linear interpolation along the mapped trace", longitude=-117.6 + 0.02 * i, latitude=35.7 + 0.01 * i,
                         source_reference_description="km from the southern end of the rupture", spatial_representation="point",
                         uncertainty_type="1_sigma", uncertainty_minus=0.1, uncertainty_plus=0.1))
    pubs = [dict(citation_short="Example et al. (2099)", citation_full="Example, A. and Sample, B. (2099). A fictional paper for the template. Journal of Examples, 1, 1-10.",
                 doi="10.0000/example", kind="publication", note=ws_spec.EXAMPLE_MARK)]
    return rows, pubs


def fill(wb, rows, pubs):
    ws = wb["INGESTION"]
    for r in rows:
        ws.append([r.get(c, "") for c in ws_spec.INGESTION_COLUMNS])
    npub = wb["NEW_PUBLICATIONS"]
    for p in pubs:
        npub.append([p.get(c, "") for c in ws_spec.SIDE_COLUMNS["NEW_PUBLICATIONS"]])


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = Path(args[0]) if args else schema.ROOT / "templates" / "ingestion_template.xlsx"
    out.parent.mkdir(parents=True, exist_ok=True)
    wb, ev, so = build_workbook()
    wb.save(out)
    print(f"template written: {out}  ({len(ev)} events, {len(read_table('metrics'))} metrics, {len(so)} publications)")
    if "--example" in sys.argv:
        wb2, ev, so = build_workbook()
        rows, pubs = example_rows(ev, so)
        fill(wb2, rows, pubs)
        ex = out.parent / "ingestion_example_filled.xlsx"
        wb2.save(ex)
        print(f"example written: {ex}")


if __name__ == "__main__":
    main()
